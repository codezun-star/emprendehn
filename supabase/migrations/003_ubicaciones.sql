-- =============================================================================
-- 003 · Ubicaciones: departamentos (18) y municipios (298) de Honduras
-- -----------------------------------------------------------------------------
-- El municipio es la "ciudad" de las URLs: /categoria/panaderias/san-pedro-sula
-- Usar un catálogo (y no texto libre) evita que "SPS", "San Pedro" y
-- "San Pedro Sula" generen páginas distintas y dispersen el SEO.
--
-- · Slug único a nivel nacional. Si el nombre se repite en varios
--   departamentos se agrega el departamento: san-jose-copan, san-jose-la-paz.
-- · Distrito Central se muestra como "Tegucigalpa" (así se busca en Google);
--   Comayagüela va en el campo "localidad" del negocio.
-- · destacado = ciudades principales (inicio y primeras opciones del selector).
-- Datos: división político-administrativa vigente (298 municipios).
-- Requiere: 001, 002
-- =============================================================================

create table if not exists public.departamentos (
  id     smallint primary key,
  nombre text not null unique,
  slug   text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

create table if not exists public.municipios (
  id              smallint generated by default as identity primary key,
  departamento_id smallint not null references public.departamentos (id) on delete restrict,
  nombre          text not null,
  slug            text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  destacado       boolean not null default false,
  unique (departamento_id, nombre)
);

create index if not exists municipios_departamento_idx on public.municipios (departamento_id);

comment on table public.municipios is 'Catálogo de municipios. Es la "ciudad" usada en URLs y filtros.';

