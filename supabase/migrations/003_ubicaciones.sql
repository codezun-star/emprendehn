con_slug as (
  select
    d.departamento_id,
    d.nombre,
    d.destacado,
    public.slugify(d.nombre) as base,
    count(*) over (partition by public.slugify(d.nombre)) as repeticiones
  from datos d
)
insert into public.municipios (departamento_id, nombre, slug, destacado)
select
  c.departamento_id,
  c.nombre,
  -- Nombre repetido en varios departamentos -> se agrega el departamento,
  -- salvo el municipio homónimo de su departamento (El Paraíso, El Paraíso).
  case when c.repeticiones > 1 and c.base <> dep.slug then c.base || '-' || dep.slug else c.base end,
  c.destacado
from con_slug c
join public.departamentos dep on dep.id = c.departamento_id
order by c.departamento_id, c.nombre
on conflict (slug) do nothing;

-- -----------------------------------------------------------------------------
-- RLS: lectura pública, escritura solo admin
-- -----------------------------------------------------------------------------
alter table public.departamentos enable row level security;
alter table public.municipios enable row level security;

drop policy if exists "departamentos: lectura pública" on public.departamentos;
create policy "departamentos: lectura pública"
  on public.departamentos for select to anon, authenticated using (true);

drop policy if exists "municipios: lectura pública" on public.municipios;
create policy "municipios: lectura pública"
  on public.municipios for select to anon, authenticated using (true);

-- Escritura solo admin (una política por operación para no duplicar el SELECT)
drop policy if exists "municipios: admin inserta" on public.municipios;
create policy "municipios: admin inserta"
  on public.municipios for insert to authenticated
  with check ((select public.is_admin()));

drop policy if exists "municipios: admin edita" on public.municipios;
create policy "municipios: admin edita"
  on public.municipios for update to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "municipios: admin elimina" on public.municipios;
create policy "municipios: admin elimina"
  on public.municipios for delete to authenticated
  using ((select public.is_admin()));

-- departamentos: catálogo fijo, solo lectura desde la app.
revoke insert, update, delete on public.departamentos from anon, authenticated;
revoke insert, update, delete on public.municipios from anon;
grant select on public.departamentos, public.municipios to anon, authenticated;
grant insert, update, delete on public.municipios to authenticated;
